assert.equal(recargado.categorias.find(c=>c.nombre==='Examen').notas[0].valor,6);
ramo.seccion=null;
const ref=ramo.categorias;
assert.equal(run('actualizarProcedenciaSugerida')(ramo,[{...opcion(estructura,3),ramo_key:c.clave,periodo:c.periodo,seccion:2}]),false);
assert.equal(run('actualizarProcedenciaSugerida')(ramo,[{...opcion(estructura,3),ramo_key:c.clave,periodo:c.periodo,seccion:null}]),true);

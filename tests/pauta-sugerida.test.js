async function red(){
  await verificarReporte;
  const r=vacio();
  S.ramos=[r];
  const registrar=async data=>{
    ctx.dataPrueba=data;
    run("supabaseClient={rpc:async()=>({data:dataPrueba})}");
    return run('leerPautaSugerida')(contexto(r),r);
  };
  assert.equal((await registrar([opcion()])).length,1);
  assert.equal(r.categorias.length,0,'la lectura no aplica una pauta');
  assert.equal((await registrar([opcion(estructura,2),opcion(otra,2),opcion(estructura,1)])).length,2);
  assert.equal((await registrar([opcion(estructura,3),opcion(otra,2)]))[0].respaldos,3);
  r.pautaSugerida={descartada:2};
  assert.equal((await registrar([opcion(otra,2)])).length,0);
  assert.equal((await registrar([opcion(otra,3)])).length,1);
  run("supabaseClient={rpc:async()=>({error:{code:'PGRST202'}})}");
  assert.equal((await run('leerPautaSugerida')(contexto(r),r)).length,0);
  S.tipoCuenta='profesor';
  assert.equal(run('elegiblePautaSugerida')(r),false);
  S.tipoCuenta='estudiante';
  r.gates=[{type:'group_min'}];
  assert.equal(run('elegiblePautaSugerida')(r),false);
  r.gates=[];
  const consenso={...opcion(estructura,3),ramo_key:contexto(r).clave,periodo:r.periodo,seccion:null};
  assert.equal(run('ponerConsensoEnRamo')(r,[consenso]),true);
  assert.equal(r.consensoRespaldos,3);
  assert.equal(r.pautaSugerida.aceptada,undefined,'el consenso normal sigue aplicándose');

  const pendiente=vacio();
  S.ramos=[pendiente];
  let responder;
  ctx.rpcPendiente=()=>new Promise(resolve=>{responder=resolve;});
  run('supabaseClient={rpc:rpcPendiente}');
  const zona={style:{},innerHTML:''};
  const espera=run('pintarPautaSugerida')(pendiente,zona);
  await new Promise(resolve=>setImmediate(resolve));
  responder({data:[]}); // consulta de consenso
  await new Promise(resolve=>setImmediate(resolve));
  pendiente.seccion=2;
  responder({data:[opcion()]});
  await espera;
  assert.equal(zona.innerHTML,'','una respuesta de la sección anterior no llega a la ficha');
  assert.equal(pendiente.categorias.length,0);
  S.tenant='udd';
  assert.equal(run('opcionPautaSugerida')(opcion(),r),null,'una compuerta explícita no sustituye el mínimo institucional');

  S.tenant='fen';
  const programa=vacio();
  const adoptada=vacio();
  adoptada.origen={tenant:'fen',ramoKey:contexto(adoptada).clave};
  S.ramos=[adoptada];
  assert.equal(aceptar(adoptada,opcion(),contexto(adoptada)),true);
  const notaPropia={id:'nota-propia',nombre:'Prueba',valor:6,peso:1,slot:0};
  adoptada.categorias.find(c=>c.nombre==='Prueba').notas.push(notaPropia);
  const oficial={evals:[['Proyecto',60],['Examen',40]],corrigePautas:[[['Examen',40],['Prueba',60]]]};
  ctx.programaSintetico=oficial;
  run("PRESETS_POR_TENANT.fen['Ramo sintético']=programaSintetico");
  assert.equal(run('elegiblePautaSugerida')(programa),false,'programa sin origen también bloquea');
  programa.origen=adoptada.origen;
  assert.ok(run('pautaPendiente')(programa),'programa nuevo para un ramo vacío');
  assert.equal(run('elegiblePautaSugerida')(programa),false);
  const cargada=run('normalize')(clone(S)).ramos[0];
  assert.equal(cargada.categorias.find(c=>c.nombre==='Prueba').notas[0].id,notaPropia.id,'corrigePautas espera confirmación');
  assert.equal(run('definicionPresetDelRamo')(cargada),null,'las reglas de programa esperan confirmación');
  assert.equal(run('pautaOficialIntacta')(cargada),false);
  const cambio=run('cambioDePauta')(cargada);
  assert.ok(cambio);
  assert.equal(cambio.notasFueraDePauta,true);
  run('aplicarCambioDePauta')(cargada,cambio);
  const conservada=cargada.categorias.find(c=>c.nombre==='Prueba');
  assert.equal(conservada.peso,0);
  assert.equal(conservada.notas[0].id,notaPropia.id);
  assert.equal(cargada.pautaSugerida?.aceptada,undefined);
  assert.equal(run('pautaOficialIntacta')(cargada),true);
  cargada.categorias.find(c=>c.nombre==='Proyecto').slots=2;
  assert.equal(run('pautaOficialIntacta')(cargada),false,'editar solo la cantidad también quita el chip oficial');
  run("delete PRESETS_POR_TENANT.fen['Ramo sintético']");
}
red().then(()=>console.log('OK: pauta sugerida, precedencia, voto, recarga y concurrencia')).catch(e=>{console.error(e);process.exitCode=1;});

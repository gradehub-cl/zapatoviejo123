assert.equal(run('pautaPropiaParaConsenso')(ramo),false);
assert.equal(run('repiteVotoSugerido')(ramo,estructura),true);
run("reporteRamoId='r';reporteDraft=estructuraDe(S.ramos[0]);showToast=()=>{};supabaseClient={rpc(){throw Error('el borrador adoptado no debe enviarse')}}");
const verificarReporte=run("enviarReporte('r')");
assert.equal(run('datosCierreRamo')(ramo,[ramo],'2026-2').pauta_origen,'editada');
disco.set('gradehub_v1',JSON.stringify(S));
const recargado=run('loadData().data.ramos[0]');

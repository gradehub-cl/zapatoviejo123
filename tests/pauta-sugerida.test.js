assert.deepEqual(clone(ramo.categorias),clone(otroDispositivo.categorias),'IDs estables');
assert.equal(ramo.consensoRespaldos,undefined);
assert.equal(run('pautaPropiaParaConsenso')(ramo),false);
const examen=ramo.categorias.find(c=>c.nombre==='Examen');
examen.notas.push({id:'nota',nombre:'Examen',valor:6,peso:1});

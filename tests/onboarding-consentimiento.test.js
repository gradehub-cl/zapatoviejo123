const fs=require('fs'),vm=require('vm'),assert=require('assert');
const app=fs.readFileSync(__dirname+'/../app.js','utf8'),html=fs.readFileSync(__dirname+'/../index.html','utf8');
const campos={'ob-name':{value:'Persona sintética'},'ob-edad':{checked:true},'ob-legal':{checked:false}};
const ctx={document:{getElementById:id=>campos[id]},selectedTenant:'fen',selectedCarrera:'IICG',selectedSem:2,selectedCarreraNombre:'Contador Auditor'};
vm.createContext(ctx);vm.runInContext(app.match(/function obStepValid\(step,datos\)\{[\s\S]*?\n\}/)[0],ctx);
assert.equal(ctx.obStepValid(1),false,'declarar 14 años no equivale a autorizar el uso de datos');
campos['ob-legal'].checked=true;assert.equal(ctx.obStepValid(1),true);
campos['ob-edad'].checked=false;assert.equal(ctx.obStepValid(1),false);
const control=html.match(/<input[^>]*id="ob-legal"[^>]*>/)?.[0];
assert(control&&!/\bchecked\b/.test(control),'consentimiento de onboarding explícito y desmarcado');
assert(/id="ob-legal"[\s\S]{0,1000}autorizo[\s\S]{0,500}notas y ramos/i.test(html),'el propósito acompaña la acción');
const sesion=fs.readFileSync(__dirname+'/../app-session.js','utf8');
ctx.currentUser=null;ctx.obIniciar=()=>{};
const pantalla={classList:{add(){},remove(){}}};
ctx.document.getElementById=id=>campos[id]||pantalla;
vm.runInContext(sesion.match(/function enterOnboarding\(\)\{[\s\S]*?\n\}/)[0],ctx);
campos['ob-legal'].checked=true;ctx.enterOnboarding();
assert.equal(campos['ob-legal'].checked,false,'otra cuenta no hereda una casilla marcada en la misma página');
console.log('Onboarding: edad y consentimiento son decisiones diferentes OK');
